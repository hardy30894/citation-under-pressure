extra = []


def emit2(name, value):
    extra.append(f"\\newcommand{{\\{name}}}{{{value}}}")


rs_path = R / "revision_stats.json"
if rs_path.exists():
    rs = json.loads(rs_path.read_text())
    emit2("nPressured", f"{rs['n_pressured_drafts']:,}")
    emit2("nHolmTests", str(next(iter(rs["holm"].values()))["n_tests"]))
    emit2("humanLenient", f"{rs['human_lenient']:.3f}")
    emit2("humanNearMissShare", f"{100 * rs['human_near_miss_share']:.0f}")
    for key, v in rs["holm"].items():
        kind, m, c = key.split(":")
        mk = ALPHA.get(m)
        if mk:
            kk = "Cite" if kind == "citation" else "Quote"
            emit2(f"holm{kk}{mk}{CONDS[c]}", f"{v['holm_p']:.3f}" if v["holm_p"] >= 0.001 else "<0.001")
    for cell, v in rs["cells"].items():
        m, c = cell.split(":")
        mk = ALPHA.get(m)
        if mk and v.get("lenient") is not None:
            emit2(f"lenient{mk}{CONDS[c]}", f"{v['lenient']:.3f}")
    for key, v in rs["loop_counts"].items():
        m, arm = key.split(":")
        mk = ALPHA.get(m)
        ak = {"true": "True", "scrambled": "Scr", "none": "None", "half": "Half", "quarter": "Quarter", "threequarter": "Threeq"}.get(arm)
        if mk and ak:
            emit2(f"lqScored{mk}{ak}Start", str(v["quotes_scored_r0"]))
            emit2(f"lqScored{mk}{ak}Final", str(v["quotes_scored_final"]))
            emit2(f"lqAcc{mk}{ak}Start", str(v["accurate_r0"]))
            emit2(f"lqAcc{mk}{ak}Final", str(v["accurate_final"]))
            emit2(f"lCites{mk}{ak}Start", str(v["cites_r0"]))
            emit2(f"lCites{mk}{ak}Final", str(v["cites_final"]))
            if v.get("exist_r0") == v.get("exist_r0"):
                emit2(f"lExist{mk}{ak}Start", fmt3(v["exist_r0"]))
                emit2(f"lExist{mk}{ak}Final", fmt3(v["exist_final"]))
    for key, v in rs.get("loop_tests", {}).items():
        m, contrast = key.split(":")
        mk = ALPHA.get(m)
        ck = {"true_vs_scrambled": "Scr", "true_vs_none": "None", "true_vs_half": "Half"}[contrast]
        if mk:
            emit2(f"ldiff{mk}{ck}", f"{v['mean_diff']:.2f}")
            emit2(f"lci{mk}{ck}", f"{v['ci_low']:.2f} to {v['ci_high']:.2f}")
            emit2(f"lp{mk}{ck}", f"{v['wilcoxon_p']:.3f}" if v["wilcoxon_p"] >= 0.001 else f"{v['wilcoxon_p']:.4f}")
            emit2(f"ln{mk}{ck}", str(v["n_pairs"]))
    emit2("unverifiablePct", f"{rs['unverifiable_share_pct']:.1f}")
    emit2("nCitationRecords", f"{rs['n_citation_records']:,}")
    emit2("sonnetTempChecked", str(rs["sonnet_temporal_checked"]))
    emit2("sonnetTempViol", str(rs["sonnet_temporal_viol"]))
    gm = rs["glm_missing"]
    emit2("glmMissing", str(sum(gm.values())))
    emit2("glmMissingCombo", str(gm["combo"]))
    for key, v in rs["memorization"].items():
        m, c = key.split(":")
        mk = ALPHA.get(m)
        if mk and v["canonical_share"] is not None:
            emit2(f"canon{mk}{CONDS[c]}", f"{100 * v['canonical_share']:.0f}")
    raw = rs["raw_counts"]
    for m, mk in ALPHA.items():
        for c, ck in CONDS.items():
            d = raw.get(f"{m}:{c}:citation", {})
            emit2(f"nf{mk}{ck}", str(d.get("not_found", 0)))
            emit2(f"ex{mk}{ck}", str(d.get("exists", 0)))

pp = R / "paraphrase_comparison.json"
if pp.exists():
    para = json.loads(pp.read_text())
    for m, mk in ALPHA.items():
        if m in para:
            for which, wk in (("original", "Orig"), ("paraphrase", "Para")):
                c = para[m][which].get("combo", {})
                if c.get("exist") is not None:
                    emit2(f"para{wk}Exist{mk}Combo", fmt3(c["exist"]))
                if c.get("strict") is not None:
                    emit2(f"para{wk}Strict{mk}Combo", fmt3(c["strict"]))

gl = R / "full_glm47flash" / "drafts"
if gl.exists():
    emit2("glmDrafts", str(len(list(gl.glob("*.txt")))))

dc = R / "notincorpus_decomposition.json"
if dc.exists():
    d = json.loads(dc.read_text())
    for m, mk in ALPHA.items():
        if m in d:
            x = d[m]
            tot = x["paraphrase_in_quotes"] + x["fabricated_language"] + x["out_of_scope_non_us"]
            emit2(f"decompPara{mk}", str(x["paraphrase_in_quotes"]))
            emit2(f"decompFab{mk}", str(x["fabricated_language"]))
            emit2(f"decompOut{mk}", str(x["out_of_scope_non_us"]))
            if tot:
                emit2(f"decompParaPct{mk}", f"{100 * x['paraphrase_in_quotes'] / tot:.0f}")

pr = R / "provenance_report.md"
if pr.exists():
    import re as _re
    from collections import Counter as _C
    cnt = _C()
    for line in open(pr):
        m_ = _re.match(r"- \*\*(\w+)\*\* \| (\w+) ", line)
        if m_:
            cnt[(m_.group(2), m_.group(1))] += 1
    for m, mk in ALPHA.items():
        if any(k[0] == m for k in cnt):
            emit2(f"misattr{mk}", str(cnt[(m, "misattributed")]))
            emit2(f"falseAlarm{mk}", str(cnt[(m, "found_in_attributed")]))
            emit2(f"notInCorpus{mk}", str(cnt[(m, "not_in_scotus_corpus")]))
            emit2(f"genericMatch{mk}", str(cnt[(m, "generic_phrase_match")]))
    emit2("misattrTotal", str(sum(v for k, v in cnt.items() if k[1] == "misattributed")))
    for m, mk in ALPHA.items():
        tot = sum(v for k, v in cnt.items() if k[0] == m)
        if tot:
            emit2(f"inaccTotal{mk}", str(tot))
            emit2(f"falseAlarmPct{mk}", f"{100 * cnt[(m, 'found_in_attributed')] / tot:.1f}")

rp = R / "replicate.json"
if rp.exists():
    rep = json.loads(rp.read_text())
    sd_e, sd_s, ident, n = [], [], 0, 0
    sign_stable = 0
    for m, mk in ALPHA.items():
        if m not in rep:
            continue
        r = rep[m]
        for c, ck in (("baseline", "Base"), ("combo", "Combo")):
            emit2(f"repMeanExist{mk}{ck}", fmt3(r[c]["exist_mean"]))
            emit2(f"repMeanStrict{mk}{ck}", fmt3(r[c]["strict_mean"]))
            emit2(f"repSdStrict{mk}{ck}", fmt3(r[c]["strict_sd"]))
            sd_e.append(r[c]["exist_sd"]); sd_s.append(r[c]["strict_sd"])
        ident += r["identical_any_pair"]; n += r["n_drafts_per_run"]
        signs = {(r[f"{run}_contrast"]["strict"] or 0) > 0 for run in ("full", "rep2", "rep3")}
        sign_stable += len(signs) == 1
    emit2("repMaxExistSd", fmt3(max(sd_e)))
    emit2("repMaxStrictSd", fmt3(max(sd_s)))
    emit2("repMaxExistRange", fmt3(max(rep[m][c]["exist_range"] for m in ALPHA if m in rep for c in ("baseline", "combo"))))
    emit2("repMaxStrictRange", fmt3(max(rep[m][c]["strict_range"] for m in ALPHA if m in rep for c in ("baseline", "combo"))))
    emit2("repIdentical", str(ident))
    emit2("repDrafts", str(n))
    emit2("repModels", str(len([m for m in ALPHA if m in rep])))
    emit2("repSignStable", str(sign_stable))
    emit2("repMistralIdentical", str(rep.get("mistralsmall", {}).get("identical_any_pair", 0)))

gr = R / "stats_gee_runs.json"
if gr.exists():
    g = json.loads(gr.read_text())
    surv = {"citation": [], "quote": []}
    for k, v in g.items():
        kind, m, _ = k.split(":")
        mk = ALPHA.get(m)
        if not mk:
            continue
        kk = "Cite" if kind == "citation" else "Quote"
        emit2(f"runsOr{kk}{mk}", f"{v['OR']:.2f}")
        emit2(f"runsCi{kk}{mk}", f"{v['ci_low']:.2f} to {v['ci_high']:.2f}")
        emit2(f"runsHolm{kk}{mk}", f"{v['holm_p']:.3f}" if v["holm_p"] >= 0.001 else "$<$0.001")
        if v["holm_p"] < 0.05:
            surv[kind].append(m)
    emit2("runsQuoteSurvivors", str(len(surv["quote"])))
    emit2("runsCiteSurvivors", str(len(surv["citation"])))
    qs = [g[f"quote:{m}:combo"]["OR"] for m in ALPHA if m in {x for x in surv["quote"]} and m != "sonnet"]
    if qs:
        emit2("runsQuoteOrMin", f"{min(qs):.2f}")
        emit2("runsQuoteOrMax", f"{max(qs):.2f}")

ph = R / "phrasing_stats.json"
if ph.exists():
    ps = json.loads(ph.read_text())
    emit2("phrSurvA", str(len(ps["survivors_a"])))
    emit2("phrMaxStrictDiff", f"{100 * ps['max_strict_diff_ab']:.0f}")
    emit2("phrMaxExistDiff", f"{100 * ps['max_exist_diff_ab']:.0f}")
    emit2("phrSurvB", str(len(ps["survivors_b"])))
    emit2("phrAinB", str(len(ps["a_replicated_in_b"])))
    emit2("phrAinPooled", str(len(ps["a_replicated_pooled"])))
    emit2("phrSurvPooled", str(len(ps["survivors_pooled"])))
    qc = [k for k in ps["survivors_pooled"] if k.startswith("quote:") and k.endswith(":combo")]
    emit2("phrPooledQuoteCombo", str(len(qc)))
    ec = [k for k in ps["survivors_pooled"] if k.startswith("citation:")]
    emit2("phrPooledCiteModels", str(len({k.split(":")[1] for k in ec})))
    for key, v in ps["cells_b"].items():
        m, c = key.split(":")
        mk = ALPHA.get(m)
        if mk and c in CONDS:
            if v["exist"] is not None:
                emit2(f"existB{mk}{CONDS[c]}", fmt3(v["exist"]))
            if v["strict"] is not None:
                emit2(f"strictB{mk}{CONDS[c]}", fmt3(v["strict"]))
    for key, v in ps["gee_pooled"].items():
        kind, m, c = key.split(":")
        mk = ALPHA.get(m)
        if mk:
            kk = "Cite" if kind == "citation" else "Quote"
            emit2(f"pooledOr{kk}{mk}{CONDS[c]}", f"{v['OR']:.2f}")
            hp = ps["holm_pooled"][key]
            emit2(f"pooledHolm{kk}{mk}{CONDS[c]}", f"{hp:.3f}" if hp >= 0.001 else "<0.001")
    ors = [ps["gee_pooled"][k]["OR"] for k in qc]
    if ors:
        emit2("phrPooledQuoteOrMin", f"{min(ors):.2f}")
        emit2("phrPooledQuoteOrMax", f"{max(ors):.2f}")

gs = R / "grounded_stats.json"
if gs.exists():
    g = json.loads(gs.read_text())
    rm = R / "retrieval" / "_meta.json"
    if rm.exists():
        emit2("retrievalCorpus", f"{json.loads(rm.read_text())['indexed_opinions']:,}")
